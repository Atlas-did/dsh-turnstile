import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
const log = readFileSync('C:/Users/finef/Desktop/mini-harness/logs/mini.log', 'utf8');
const token = (log.match(/token=([A-Za-z0-9_-]+)/) || [])[1];
const b = await chromium.launch({ channel: 'msedge', headless: true });
const p = await b.newPage({ viewport: { width: 1500, height: 900 } });
const bad = [];
p.on('response', r => { if (r.status() >= 400) bad.push(r.status() + ' ' + r.url().replace(/token=[^&]*/, 'token=***').slice(0, 90)); });
await p.goto('http://127.0.0.1:18770/turnstile/?token=' + token, { waitUntil: 'load' }).catch(() => {});
await p.waitForTimeout(2500);
console.log('404s:', JSON.stringify(bad.slice(0, 4)));
console.log('overview text:', (await p.locator('#body').innerText()).replace(/\n/g, ' | ').slice(0, 120));
await p.locator('nav div').nth(3).click().catch(() => {});
await p.waitForTimeout(900);
console.log('rows:', await p.locator('table tbody tr').count());
await p.screenshot({ path: 'C:/Users/finef/Desktop/mini-harness/state/console-page.png' });
await b.close();